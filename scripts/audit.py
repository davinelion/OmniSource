# Tool configuration is discovered by filename convention, not by reference:
# nothing in the tree names `web/eslint.config.mjs` or `web/postcss.config.mjs`,
# but deleting either breaks `npm run lint` / the production build. They are
# exempt from the unused-file scan for the same reason `package.json` scripts
# are not "dead code".
TOOL_CONFIG_RE = re.compile(
    r"^(?:eslint|postcss|tailwind|next|vite|vitest|jest|playwright|prettier|babel|metro|rollup|webpack|tsup)"
    r"\.config\.(?:js|mjs|cjs|ts|mts)$"
)

CSS_CLASS_RE = re.compile(r"\.([a-zA-Z][\w-]+)")
JS_GLOBAL_DECL_RE = re.compile(r"^window\.([A-Za-z_$][\w$]*)\s*=", re.MULTILINE)
PY_TOP_FUNC_RE = re.compile(r"^def ([a-zA-Z_][\w]*)", re.MULTILINE)


def audit_files_and_globals() -> tuple[list[str], list[str], list[str], list[str]]:
    """Unused committed files, dead globals, unused CSS selectors, dead py fns."""
    unused_files: list[str] = []
    dead_globals: list[str] = []
    unused_selectors: list[str] = []
    dead_python: list[str] = []

    html_texts = all_html_texts()
    js_texts = all_js_texts()
    py_texts = {p: read(ROOT / p) for p in iter_files((".py",), trees=("src", "scripts", "tests"))}
    other_text = dict(html_texts) | dict(js_texts)
    # The generated docs hub (docs/index.html) links every Markdown doc, and
    # the module layer (js/modules/*.js) is referenced from <script type=
    # "module"> tags — both are part of the "referencing corpus".
    for p in iter_files((".html",), trees=("docs",)):
        other_text[p] = read(ROOT / p)
    for p in iter_files((".js",), trees=("js/modules",)):
        other_text[p] = read(ROOT / p)
    for p in [
        *iter_files((".md",), trees=(".",)),
        *iter_files((".md", ".json", ".xml", ".webmanifest"), trees=("docs", "schemas", "locales")),
    ]:
        other_text[p] = read(ROOT / p)

    # --- committed files never referenced anywhere -----------------------
    candidates = [
        *js_texts,
        *iter_files((".css",), trees=("assets", "website")),
        *iter_files((".png", ".webp", ".svg"), trees=("assets",)),
        *list(
            iter_files(
                (".html", ".js", ".css", ".json", ".xml", ".png", ".webp"), trees=("website", "sdk", "graph", "config")
            )
        ),
    ]
    data_blobs = read(ROOT / "feeds/discovery.json") if (ROOT / "feeds/discovery.json").exists() else ""
    icons_used = set(re.findall(r'"icon"\s*:\s*"([^"]+)"', data_blobs)) | set(
        re.findall(
            r'"icon"\s*:\s*"([^"]+)"',
            read(ROOT / "feeds/asset-manifest.json") if (ROOT / "feeds/asset-manifest.json").exists() else "",
        )
    )
    # The generated trees are part of the referencing corpus too: the site's
    # gallery is driven by feeds/screenshots.json, so a mirrored screenshot or
    # thumbnail that only that document names (the `thumbnailURL` field) was
    # reported as dead weight. They are scanned once into a set of referenced
    # paths — apps.json alone is ~800 KiB, so keeping them as text would make
    # the candidate loop pay for a multi-megabyte corpus on every file.
    generated_refs: set[str] = set()
    for path in iter_files((".json", ".xml", ".webmanifest"), trees=("feeds", "api")):
        generated_refs |= set(re.findall(r"assets/[A-Za-z0-9._~%/@+-]+", read(ROOT / path)))
    for path in sorted(set(candidates)):
        name = rel(path)
        if name in icons_used or name in generated_refs:
            continue  # referenced from generated feed data
        if TOOL_CONFIG_RE.match(path.name):
            continue  # loaded by convention (see TOOL_CONFIG_RE)
        stem = Path(name).stem + path.suffix
        basename = Path(name).name
        hits = referenced_in_files(basename, other_text) + referenced_in_files(stem, other_text)
        hits = [h for h in hits if h != path]
        if not hits:
            # a sibling twin (e.g. .png for a .webp) counts as a soft link
            twin = path.with_suffix(".webp" if path.suffix == ".png" else ".png")
            if twin.exists() and any(
                n for n in (twin.name, twin.stem + twin.suffix) if referenced_in_files(n, other_text)
            ):
                continue
            unused_files.append(name)

    # --- JS globals declared in legacy scripts ----------------------------
    for path, text in js_texts.items():
        if rel(path).startswith(("js/", "src/js/", "website/")):
            for global_name in JS_GLOBAL_DECL_RE.findall(text):
                uses = 0
                for _other_path, other_text in html_texts.items():
                    uses += len(re.findall(rf"\b{re.escape(global_name)}\b", other_text))
                for other_path, other_text in js_texts.items():
                    if other_path == path:
                        continues = len(re.findall(rf"\b{re.escape(global_name)}\b", other_text)) - len(
                            re.findall(rf"window\.{re.escape(global_name)}\s*=", other_text)
                        )
                        uses += max(0, continues)
                if uses <= 0:
                    dead_globals.append(f"{rel(path)}: window.{global_name} is assigned but never read")

    # --- CSS selectors with zero occurrences in any markup/script ---------
    markup_all = "\n".join(html_texts.values()) + "\n".join(js_texts.values()) + "\n".join(py_texts.values())
    for css_path in sorted(iter_files((".css",), trees=("assets",))):
        text = read(ROOT / css_path)
        stripped = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
        for cls in sorted(set(CSS_CLASS_RE.findall(stripped))):
            if len(cls) < 3:
                continue
            if (
                not re.search(
                    rf'class="[^"]*\b{re.escape(cls)}\b|class="[^"]*{re.escape(cls)}|data-[a-z-]+"\s*[:=].*{re.escape(cls)}|["\'\s.]{re.escape(cls)}["\'\s]',
                    markup_all,
                )
                and cls not in markup_all
            ):
                unused_selectors.append(f"{rel(css_path)}: .{cls}")

    # --- Python top-level functions never referenced ----------------------
    all_searchable = "\n".join(py_texts.values()) + "\n".join(js_texts.values()) + "\n".join(html_texts.values())
    for path, text in sorted(py_texts.items()):
        if not rel(path).startswith("src/omnisource"):
            continue
        try:
            tree = ast.parse(text)
        except SyntaxError:
            continue
        module = path.with_suffix("").as_posix().split("src/")[-1].replace("/", ".")
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith("_"):
                # self-reference within the defining module doesn't count as use
                own_uses = len(
                    re.findall(rf"\b{re.escape(node.name)}\b", "\n".join(t for p, t in py_texts.items() if p != path))
                )
                export = len(re.findall(rf"{re.escape(node.name)}\b", all_searchable))
                if own_uses == 0 and export <= len(re.findall(rf"\bdef {re.escape(node.name)}\b", text)):
                    dead_python.append(f"{rel(path)}: {module}.{node.name}() has no callers outside its module")

    return unused_files, dead_globals, unused_selectors, dead_python


def write_dead_code(report_lines=None) -> Report:
    rep = Report(
        "Dead Code Report",
        "Files, globals, selectors and functions in the repository that nothing references.\n"
        "Scope: committed source trees (`js/`, `src/`, `assets/`, `website/`, `docs/`, `sdk/`, `scripts/`)\n"
        "plus the generated `feeds/` tree. Usage detection is textual: a name that appears in no\n"
        "HTML attribute, JS/Python source, feed `icon` field or doc link is flagged. Textual scans\n"
        "over-report dynamic usage, so every finding below lists the confirmation a maintainer\n"
        "should do before deleting.",
    )
    unused_files, dead_globals, unused_selectors, dead_python = audit_files_and_globals()
    rep.summary.append(f"- Unused files: **{len(unused_files)}**")
    rep.summary.append(f"- Dead JS globals: **{len(dead_globals)}**")
    rep.summary.append(f"- Unreferenced CSS selectors: **{len(unused_selectors)}**")
    rep.summary.append(f"- Uncalled public Python functions: **{len(dead_python)}**")

    sec = rep.section("Unused files")
    if unused_files:
        sec.add("| File | Why it is flagged |")
        sec.add("| --- | --- |")
        for name in unused_files:
            sec.add(f"| `{name}` | no reference in HTML, JS, CSS, feed data or docs |")
    else:
        sec.add("None. Every committed script, stylesheet, icon and helper file is referenced.")

    sec = rep.section("Dead JS globals")
    for line in dead_globals or ["None — every `window.*` namespace is consumed."]:
        sec.add(f"- {line}")

    sec = rep.section("Unreferenced CSS selectors")
    if unused_selectors:
        for line in unused_selectors[:80]:
            sec.add(f"- `{line}`")
        if len(unused_selectors) > 80:
            sec.add(f"- …and {len(unused_selectors) - 80} more (audit truncation)")
    else:
        sec.add("None found across the design system.")

    sec = rep.section("Dead Python functions")
    for line in dead_python or ["None — every public function in `src/omnisource` has at least one caller or test."]:
        sec.add(f"- {line}")

    sec = rep.section("Verification checklist")
    sec.add("- Before deleting a file: `rg <name>` across the whole tree (feed JSON included).")
    sec.add("- Before deleting a selector: check class strings built at runtime (`cls + '-active'` etc.).")
    sec.add("- Before deleting a Python function: run `make test` — tests may import it directly.")
    return rep


