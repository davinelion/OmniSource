def walk_pages():
    for p in iter_files((".html",)):
        yield p, read(ROOT / p)


def resolve_target(page: Path, href: str) -> tuple[bool, str]:
    """Check an internal href against the served tree (repo root == site root)."""
    href = href.split("#", 1)[0].split("?", 1)[0]
    if not href:
        return True, "anchor"
    base = ROOT / page.parent
    target = (base / href).resolve()
    kind = "file"
    if href.endswith("/"):
        target = target / "index.html"
    if target.exists():
        return True, kind
    # GitHub Pages project site: paths may also live in feeds/api mirrors.
    return False, kind


def write_links() -> Report:
    rep = Report(
        "Links & SEO Audit",
        "Every internal href/src on committed pages is resolved against the repository tree (which is\n"
        "what GitHub Pages serves in branch mode). SEO metadata is checked page-by-page: title,\n"
        "description, canonical, Open Graph, Twitter card.",
    )
    broken: list[str] = []
    seo_missing: dict[str, list[str]] = {}
    external_refs = 0
    for page, text in walk_pages():
        # Attribute names are case-insensitive in HTML, so scan them that way.
        for match in re.finditer(r'(?:href|src|data-feed)="([^"]+)"', text, re.IGNORECASE):
            url = match.group(1)
            if not url.startswith(("#", "/OmniSource", "/", "./", "../")):
                # Custom client schemes (altstore://, sidestore://, feather://,
                # esign://, livecontainer://, itms-services://, ...) are not
                # page links — they are handled by the sideloading client.
                external_refs += 1
                continue
            if url.startswith(("http://", "https://", "mailto:", "data:", "javascript:", "//")):
                external_refs += 1
                continue
            if url.startswith("#") or url.startswith("{{") or "${" in url:
                continue  # template-literal paths resolve at runtime
            ok, _kind = resolve_target(page, url)
            if not ok:
                broken.append(f"`{rel(page)}` → `{url}`")
        for match in re.finditer(r'srcset="([^"]+)"', text, re.IGNORECASE):
            for cand in match.group(1).split(","):
                u = cand.strip().split(" ")[0]
                if u and not u.startswith(("http", "//", "data:")):
                    ok, _ = resolve_target(page, u)
                    if not ok:
                        broken.append(f"`{rel(page)}` srcset → `{u}`")
        if "data-page" not in text:  # generated pages without site chrome don't need full SEO kit
            pass
        needs = ["<title", 'name="description"', 'rel="canonical"', 'property="og:title"', 'name="twitter:card"']
        miss = [n for n in needs if n not in text]
        if miss:
            seo_missing[rel(page)] = miss

    # sitemap cross-check
    sitemap_urls = (
        re.findall(r"<loc>([^<]+)</loc>", read(ROOT / "sitemap.xml")) if (ROOT / "sitemap.xml").exists() else []
    )
    base_marker = "/OmniSource/"
    sitemap_missing = []
    for url in sitemap_urls:
        tail = url.split(base_marker, 1)[-1]
        candidate = ROOT / tail if tail else ROOT / "index.html"
        if not candidate.name:
            candidate = candidate / "index.html"
        if not candidate.exists():
            sitemap_missing.append(url)

    rep.summary.append(f"- Broken internal link targets: **{len(set(broken))}**")
    rep.summary.append(
        f"- Pages missing SEO metadata: **{len(seo_missing)}** (of {len(list(walk_pages()))} HTML files)"
    )
    rep.summary.append(f"- Sitemap URLs not resolvable in the tree: **{len(sitemap_missing)}**")
    rep.summary.append(f"- External references (not resolved offline): {external_refs}")

    sec = rep.section("Broken internal links")
    for line in sorted(set(broken))[:60] or [
        "None. Every relative href/src/srcset on every page resolves against the repository tree."
    ]:
        sec.add(f"- {line}")
    if len(set(broken)) > 60:
        sec.add(f"- …and {len(set(broken)) - 60} more.")

    sec = rep.section("SEO metadata gaps")
    if seo_missing:
        sec.add("| Page | Missing |")
        sec.add("| --- | --- |")
        for page, miss in sorted(seo_missing.items()):
            sec.add(f"| `{page}` | {', '.join(f'`{m}`' for m in miss)} |")
    else:
        sec.add("Every scanned page ships title, description, canonical, Open Graph and Twitter card tags.")

    sec = rep.section("Sitemap")
    sec.add(f"- {len(sitemap_urls)} URLs listed in `sitemap.xml`.")
    if sitemap_missing:
        for u in sitemap_missing[:20]:
            sec.add(f"- ⚠️ listed but missing: `{u}`")
    else:
        sec.add("- All listed URLs resolve in the repository tree (branch-deployment mode).")

    sec = rep.section("Redirect/alias notes")
    sec.add(
        "- Extensionless API routes (`/api/apps`, …) ship as committed twin files because Pages cannot rewrite; see `docs/API.md`."
    )
    return rep


