# Directories that never count as "code" for ownership/usage scans.
SKIP_DIRS = {
    ".git",
    "node_modules",
    "__pycache__",
    ".cache",
    "_site",
    ".next",
    ".output",
    "dist",
    "build",
    "coverage",
    ".ruff_cache",
    ".mypy_cache",
}
# Generated trees: files there are outputs, not hand-maintained code.
GENERATED_TREES = ("feeds/", "api/", "apps/", "collections/", "compare/", "reports/")

GENERATED_NOTE = "_Generated by `scripts/audit.py` — do not edit by hand; rerun `make audit` to refresh._"


def commit_pathspecs(text: str) -> set[str]:
    """Pathspecs of every ``git add`` command in a workflow.

    Shell-quoted so ``'*.json'`` stays one token: line continuations are joined
    and comment lines dropped before ``shlex.split`` runs. The previous
    character-class regex scanned the whole file for anything single-quoted and
    collected unrelated strings (``'fail'``, ``'apps'``, ``'n/a'`` …) from
    *every* workflow — the drift check below then reported directories that
    sync.yml does stage, and skipped ones it does not.
    """
    import shlex

    joined = re.sub(r"\\\n\s*", " ", text)
    pathspecs: set[str] = set()
    for line in joined.splitlines():
        stripped = line.strip()
        if stripped.startswith("#") or "git add" not in stripped:
            continue
        try:
            tokens = shlex.split(stripped)
        except ValueError:  # unbalanced quotes in a shell snippet
            continue
        if len(tokens) < 3 or tokens[0] != "git" or tokens[1] != "add":
            continue
        pathspecs |= {token for token in tokens[2:] if not token.startswith("-")}
    return pathspecs


def rel(path: Path) -> str:
    if path.is_absolute():
        try:
            return path.relative_to(ROOT).as_posix()
        except ValueError:
            return str(path)
    return path.as_posix()


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace")


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _keep(path: Path) -> bool:
    return not any(part in SKIP_DIRS for part in path.parts)


def iter_files(suffixes: tuple[str, ...], trees: tuple[str, ...] = (".",)) -> list[Path]:
    out: list[Path] = []
    for tree in trees:
        base = ROOT / tree
        if base.is_file():
            if base.suffix in suffixes:
                out.append(base.relative_to(ROOT))
            continue
        if not base.is_dir():
            continue
        for path in sorted(base.rglob("*")):
            rel_path = path.relative_to(ROOT)
            if not _keep(rel_path):
                continue
            if path.is_file() and path.suffix in suffixes:
                out.append(rel_path)
    return list(dict.fromkeys(out))


def html_pages(scope: tuple[str, ...] = (".",)) -> list[Path]:
    pages: list[Path] = []
    for tree in scope:
        base = ROOT / tree
        if base.is_file() and base.suffix == ".html":
            pages.append(base.relative_to(ROOT))
            continue
        if not base.is_dir():
            continue
        for path in sorted(base.rglob("*.html")):
            rel_path = path.relative_to(ROOT)
            if not _keep(rel_path):
                continue
            pages.append(rel_path)
    return pages


def load_json(path: Path):
    try:
        return json.loads(read(ROOT / path))
    except (OSError, ValueError):
        return None


