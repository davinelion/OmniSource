ATTR_RE = re.compile(r'data-i18n(?:-placeholder|-aria-label|-alt|-title)?="([^"]+)"')
CALL_RE = re.compile(r"""\b(?:t|translate)\(\s*["']([A-Za-z][\w.]*)["']""")
MARKER_RE = re.compile(r"i18n-keys:\s*([^<\n]+)")
SETATTR_RE = re.compile(r"""setAttribute\(\s*["']data-i18n(?:-[a-z-]+)?["']\s*,\s*["']([^"']+)["']""")
PLACEHOLDER_RE = re.compile(r"\$\{(\w+)\}")


def flatten(obj, prefix="", out=None):
    out = {} if out is None else out
    for key, value in obj.items():
        full = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict):
            flatten(value, full, out)
        else:
            out[full] = value
    return out


def write_localization() -> Report:
    rep = Report(
        "Localization Audit",
        "Key parity, fallback coverage and per-page i18n wiring across every committed locale\n"
        "(`locales/*.json`) and every HTML page. The contract enforced by\n"
        "`tests/test_translations.py` and `scripts/validate-translations.js` is reproduced here in\n"
        "report form: missing keys, orphaned keys, placeholder drift and untranslated chrome.",
    )
    locales = {
        p.stem: flatten(load_json(Path("locales") / p.name) or {}) for p in sorted((ROOT / "locales").glob("*.json"))
    }
    en = locales.get("en", {})
    used: dict[str, list[str]] = defaultdict(list)
    per_page: dict[str, int] = defaultdict(int)
    for path in html_pages():
        text = read(ROOT / path)
        for match in MARKER_RE.finditer(text):
            for key in match.group(1).split(","):
                key = key.strip()
                if key and "-" not in key and "." in key:
                    used[key].append(rel(path))
        for match in ATTR_RE.finditer(text):
            used[match.group(1)].append(rel(path))
            per_page[rel(path)] += 1
        for match in CALL_RE.finditer(text):
            used[match.group(1)].append(rel(path))
            per_page[rel(path)] += 1
        for match in SETATTR_RE.finditer(text):
            used[match.group(1)].append(rel(path))
            per_page[rel(path)] += 1
    for path in iter_files((".js", ".mjs"), trees=("js", "src", "website")):
        text = read(ROOT / path)
        for match in CALL_RE.finditer(text):
            used[match.group(1)].append(rel(path))
        for match in SETATTR_RE.finditer(text):
            used[match.group(1)].append(rel(path))
        # `// i18n-keys:` markers declare keys rendered only into dynamic HTML.
        for match in MARKER_RE.finditer(text):
            for key in match.group(1).split(","):
                key = key.strip()
                if key and "-" not in key and "." in key:
                    used[key].append(rel(path))

    missing_global = {loc: sorted(k for k in en if k not in data) for loc, data in locales.items()}
    unknown_used = sorted(set(used) - set(en))
    dead_keys = sorted(set(en) - set(used))
    english_values = dict(en)
    untranslated = {
        loc: sorted(
            k for k, v in data.items() if k in english_values and str(v) == str(english_values[k]) and loc not in {"en"}
        )
        for loc, data in locales.items()
    }

    rep.summary.append(f"- Locales: **{len(locales)}** ({', '.join(sorted(locales))})")
    rep.summary.append(f"- Canonical keys (en): **{len(en)}**")
    rep.summary.append(f"- Missing keys across locales: **{sum(len(v) for v in missing_global.values())}**")
    rep.summary.append(f"- Keys used by markup/JS but missing from en.json: **{len(unknown_used)}**")
    rep.summary.append(f"- Orphaned en.json keys (no call site): **{len(dead_keys)}**")

    sec = rep.section("Per-locale coverage")
    sec.add("| Locale | Keys | Coverage | Placeholder drift | Identical-to-English values |")
    sec.add("| --- | --- | --- | --- | --- |")
    for loc, data in sorted(locales.items()):
        missing = missing_global.get(loc, [])
        drift = []
        for key, template in en.items():
            want = set(PLACEHOLDER_RE.findall(str(template)))
            got = set(PLACEHOLDER_RE.findall(str(data.get(key, ""))))
            if want != got:
                drift.append(key)
        same = untranslated.get(loc, [])
