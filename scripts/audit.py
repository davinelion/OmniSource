def compute_findings() -> dict[str, list]:
    """Derive recommendation lines from the current tree state."""
    findings: dict[str, list] = {"P0": [], "P1": [], "P2": [], "P3": []}
    unused_files, _dead_globals, _unused_selectors, dead_python = audit_files_and_globals()
    if unused_files:
        findings["P0"].append(
            f"- Remove or wire the {len(unused_files)} unreferenced file(s) in `dead-code.md` (each is confirmed unused at the commit)."
        )
    if dead_python:
        findings["P0"].append(
            f"- Delete {len(dead_python)} uncalled public function(s) or document them as extension points."
        )
    groups = duplicate_json_groups()
    if groups:
        findings["P2"].append(
            f"- {len(groups)} JSON mirror group(s) remain by design (branch Pages compatibility); do not delete without updating `src/omnisource/site.py`, `publish_root.py` and the smoke test in the same PR. **RESOLVED as accepted technical debt** — documented in `duplicates.md`."
        )
    localization = load_json(Path("feeds/translation-status.json")) or {}
    low = [k for k, v in localization.items() if isinstance(v, int) and v < 100]
    if low:
        findings["P1"].append(
            f"- Locales below 100% coverage: {', '.join(low)} — add the missing keys to `locales/*.json`."
        )
    return findings


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--only", choices=("dead", "dup", "l10n", "perf", "wf", "a11y", "links", "recs", "all"), default="all"
    )
    parser.add_argument(
        "--check", action="store_true", help="print a one-line summary and exit non-zero if P0 findings exist"
    )
    args = parser.parse_args(argv)

    REPORTS_DIR.mkdir(exist_ok=True)
    which = args.only
    written: list[str] = []
    if which in ("dead", "all"):
        written.append((_REPORT := REPORTS_DIR / "dead-code.md").name) or _REPORT.write_text(
            write_dead_code().render(), encoding="utf-8"
        )
    if which in ("dup", "all"):
        written.append((_REPORT := REPORTS_DIR / "duplicates.md").name) or _REPORT.write_text(
            write_duplicates().render(), encoding="utf-8"
        )
    if which in ("l10n", "all"):
        written.append((_REPORT := REPORTS_DIR / "localization.md").name) or _REPORT.write_text(
            write_localization().render(), encoding="utf-8"
        )
    if which in ("perf", "all"):
        written.append((_REPORT := REPORTS_DIR / "performance.md").name) or _REPORT.write_text(
            write_performance().render(), encoding="utf-8"
        )
    if which in ("wf", "all"):
        written.append((_REPORT := REPORTS_DIR / "workflows.md").name) or _REPORT.write_text(
            write_workflows().render(), encoding="utf-8"
        )
    if which in ("a11y", "all"):
        written.append((_REPORT := REPORTS_DIR / "accessibility.md").name) or _REPORT.write_text(
            write_accessibility().render(), encoding="utf-8"
        )
    if which in ("links", "all"):
        written.append((_REPORT := REPORTS_DIR / "links.md").name) or _REPORT.write_text(
            write_links().render(), encoding="utf-8"
        )
    findings = compute_findings()
    if which in ("recs", "all"):
        written.append((_REPORT := REPORTS_DIR / "recommendations.md").name) or _REPORT.write_text(
            write_recommendations(findings).render(), encoding="utf-8"
        )

    p0 = len(findings["P0"])
    if args.check:
        print(f"audit: {p0} P0 finding(s)")
        return 1 if p0 else 0
    # Only the files this script owns are listed: reports/final-audit.md is the
    # hand-written modernization summary and must never look auto-generated.
    print("audit: wrote " + ", ".join(sorted(written)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
