def duplicate_json_groups() -> list[tuple[str, list[str]]]:
    hashes: dict[str, list[str]] = defaultdict(list)
    json_files = [p for p in iter_files((".json",)) if ".git" not in p.parts]
    for path in json_files:
        full = ROOT / path
        try:
            hashes[sha256(full)].append(rel(path))
        except OSError:
            continue
    return sorted(((h, files) for h, files in hashes.items() if len(files) > 1), key=lambda item: -len(item[1]))


def duplicate_functions() -> list[tuple[int, str, list[str]]]:
    """Normalized duplicate top-level Python function bodies."""
    seen: dict[str, list[str]] = defaultdict(list)
    for path in iter_files((".py",), trees=("src", "scripts")):
        text = read(ROOT / path)
        try:
            tree = ast.parse(text)
        except SyntaxError:
            continue
        for node in tree.body:
            if isinstance(node, ast.FunctionDef):
                body = [ast.dump(child) for child in node.body]
                key = hashlib.sha256("|".join(body).encode()).hexdigest()
                seen[key].append(f"{rel(path)}:{node.name}")
    out = []
    for _key, names in seen.items():
        if len(names) > 1:
            fn = names[0].split(":")[1]
            out.append((len(names), fn, names))
    return sorted(out, reverse=True)


def gz_overhead() -> tuple[int, int]:
    total_files = 0
    total_bytes = 0
    for path in iter_files((".gz",)):
        total_files += 1
        total_bytes += (ROOT / path).stat().st_size
    return total_files, total_bytes


def write_duplicates() -> Report:
    rep = Report(
        "Duplicate Output Report",
        "Byte-level duplication in committed artifacts, duplicated source code, and the weight\n"
        "of generated copies. Duplicate JSON mirrors exist so that GitHub Pages (branch mode) can\n"
        "serve every historical URL without a build step; they are generated, never hand-edited,\n"
        "and every deletion here must go through `src/omnisource/site.py` first.",
    )
    groups = duplicate_json_groups()
    functions = duplicate_functions()
    gz_files, gz_bytes = gz_overhead()
    rep.summary.append(f"- Byte-identical generated JSON groups: **{len(groups)}**")
    rep.summary.append(f"- Identical-function clones across `src/` + `scripts/`: **{len(functions)}**")
    rep.summary.append(f"- Compressed `.gz` mirror files committed: **{gz_files}** ({gz_bytes / 1024:.0f} KiB)")

    sec = rep.section("Byte-identical JSON mirror groups")
    if groups:
        sec.add("| Group | Copies | Role |")
        sec.add("| --- | --- | --- |")
        for _h, files in groups:
            origin = next((f for f in files if f.startswith("feeds/")), files[0])
            copies = ", ".join(f"`{f}`" for f in files if f != origin) or "—"
            sec.add(f"| `{origin}` | {len(files)} | mirrors: {copies} |")
        sec.add("")
        sec.add(
            "**Disposition:** the `feeds/` file is the source of truth; `apps.json`, `api/*` and\n"
            "their `.gz` twins are the branch-deployed URL surface and are kept for subscriber/API\n"
            "compatibility (see `docs/ARCHITECTURE.md` → Data pipeline). `check_reproducible.py`\n"
            "fails CI if any copy ever drifts, so mirrors can never diverge silently."
        )
    else:
        sec.add("No duplicated JSON remains.")

    sec = rep.section("Duplicated functions")
    if functions:
        for count, name, where in functions[:40]:
            sec.add(f"- `{name}()` x{count}: {', '.join(f'`{w}`' for w in where)}")
    else:
        sec.add("No duplicated function bodies across `src/` and `scripts/`.")

    sec = rep.section("Compression mirrors")
    sec.add(f"- {gz_files} `.gz` files contribute {gz_bytes / 1024:.0f} KiB to the checkout.")
    sec.add("- `.br` twins are only written when the optional `brotli` package is installed at build time (CI opt-in).")
    sec.add(
        "- Recommendation: keep; the mirrors are smaller than the savings they provide to clients, and GitHub Pages serves them with `Content-Encoding` for gzip-capable consumers."
    )
    return rep


