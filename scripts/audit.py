def all_html_texts() -> dict[Path, str]:
    return {p: read(ROOT / p) for p in html_pages()}


def all_js_texts() -> dict[Path, str]:
    files = iter_files((".js", ".mjs", ".cjs"))
    return {p: read(ROOT / p) for p in files}


def referenced_in_files(name: str, texts: dict[Path, str]) -> list[Path]:
    return sorted(p for p, text in texts.items() if name in text)


