class A11yParser(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.imgs: list[dict] = []
        self.links: list[dict] = []
        self.buttons: list[dict] = []
        self.inputs: list[dict] = []
        self.selects: list[dict] = []
        self.headings: list[tuple[int, str]] = []
        self.ids: list[str] = []
        self.html_attrs: dict = {}
        self.current_heading: int | None = None
        self._skip = False

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        self.ids.append(a.get("id") or "")
        if tag == "html":
            self.html_attrs = a
        elif tag == "img":
            self.imgs.append(a)
        elif tag == "a":
            self.links.append(a)
        elif tag == "button":
            self.buttons.append(a)
        elif tag == "input":
            self.inputs.append(a)
        elif tag == "select":
            self.selects.append(a)
        elif tag in ("h1", "h2", "h3", "h4", "h5", "h6"):
            self.headings.append((int(tag[1]), ""))
        elif tag in ("script", "style"):
            self._skip = True

    def handle_data(self, data):
        if self.headings and not self.headings[-1][1]:
            level, _ = self.headings[-1]
            self.headings[-1] = (level, data.strip()[:60])

    def handle_endtag(self, tag):
        if tag in ("script", "style"):
            self._skip = False


def audit_page(page: Path) -> list[str]:
    text = read(ROOT / page)
    parser = A11yParser()
    with contextlib.suppress(Exception):  # malformed snippets must not abort the audit
        parser.feed(text)
    problems: list[str] = []
    if not parser.html_attrs.get("lang"):
        problems.append("missing `lang` on `<html>`")
    img_total = len(parser.imgs)
    img_unlabeled = [i for i in parser.imgs if "alt" not in i]
    if img_unlabeled:
        problems.append(f"{len(img_unlabeled)}/{img_total} `<img>` without `alt`")
    no_label_buttons = [
        b
        for b in parser.buttons
        if not (
            b.get("aria-label") or b.get("data-i18n-aria-label") or b.get("title") or "close" in (b.get("class") or "")
        )
    ]
    if parser.buttons and len(no_label_buttons) > len(parser.buttons) * 0.6:
        problems.append("most buttons rely on inner text only (screen-reader labels recommended for icon buttons)")
    dup_ids = sorted({i for i in parser.ids if i and parser.ids.count(i) > 1})
    if dup_ids:
        problems.append("duplicate ids: " + ", ".join(f"`{d}`" for d in dup_ids[:6]))
    levels = [lvl for lvl, _t in parser.headings]
    skips = [f"h{a}→h{b}" for a, b in pairwise(levels) if b - a > 1]
    if skips:
        problems.append("heading levels skip: " + ", ".join(sorted(set(skips))[:6]))
    links_without_href = [a for a in parser.links if not a.get("href")]
    if links_without_href:
        problems.append(f"{len(links_without_href)} `<a>` without `href` (use button)")
    bare_newtab = [
        a for a in parser.links if "_blank" in (a.get("target") or "") and "noopener" not in (a.get("rel") or "")
    ]
    if bare_newtab:
        problems.append(f"{len(bare_newtab)} target=_blank links missing rel=noopener")
    inputs_unlabeled = [
        i
        for i in parser.inputs
        if i.get("type") not in ("hidden", "checkbox", "radio", "submit", "button")
        and not (i.get("aria-label") or i.get("data-i18n-aria-label") or i.get("id"))
    ]
    if inputs_unlabeled:
        problems.append(f"{len(inputs_unlabeled)} text inputs without label/aria-label")
    if "skip-link" not in text and "skip link" not in text.lower() and "<main" in text:
        problems.append("no skip link")
    # A `<dialog>` driven by showModal() from a shared script is modal by
    # definition, so the check only fires when no script in the tree opens it.
    if (
        re.search(r"<dialog\b", text, re.IGNORECASE)
        and "aria-modal" not in text
        and "showModal" not in text
        and "showModal" not in _shared_js()
    ):
        problems.append("dialog present without modal semantics (verify showModal usage in JS)")
    return problems


