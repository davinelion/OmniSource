#!/usr/bin/env python3
"""Repository audit generator.

Runs the full static-analysis suite the modernization effort relies on and
writes the Markdown reports under ``reports/``:

    reports/dead-code.md         dead/unused code: files, globals, selectors
    reports/duplicates.md        byte-identical generated JSON, duplicated
                                 functions, redundant payload copies
    reports/localization.md      locale parity, missing/orphaned keys,
                                 untranslated chrome per page
    reports/performance.md       payload weights: JSON, gzip twins, assets,
                                 CSS/JS budget checks, script loading
    reports/workflows.md         GitHub Actions inventory: triggers, perms,
                                 retention, drift between pipeline outputs
                                 and commit allowlists
    reports/accessibility.md     structural a11y checks over every HTML page
    reports/links.md             broken internal links + missing SEO metadata
    reports/recommendations.md   prioritized follow-ups derived from the above

The audit is stdlib-only, deterministic for a given tree, and network-free so
it runs identically in CI and on a laptop. Run ``python3 scripts/audit.py``
from the repository root (or ``make audit``). Exit status is 0 when reports
were written; findings never fail the audit itself — CI gates live in
``validate.py`` and the unit tests.
"""

