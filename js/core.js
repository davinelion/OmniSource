  /* ============================================================================
     Motion: scroll reveal + count-up (respecting prefers-reduced-motion).
     ========================================================================== */
  function setupReveal() {
    var nodes = $$('[data-reveal]');
    if (!nodes.length) return;
    if (OS.reducedMotion || !('IntersectionObserver' in window)) {
      nodes.forEach(function (n) { n.classList.add('is-revealed'); });
      return;
    }
    var observer = new IntersectionObserver(function (entries) {
      entries.forEach(function (entry) {
        if (entry.isIntersecting) {
          entry.target.classList.add('is-revealed');
          observer.unobserve(entry.target);
        }
      });
    }, { rootMargin: '0px 0px -36px 0px', threshold: 0.08 });
    nodes.forEach(function (n) { observer.observe(n); });
  }

  function animateCount(node, force) {
    if (node._omniCounting || (node._omniCounted && !force)) return;
    var raw = node.dataset.countValue != null ? String(node.dataset.countValue) : String(node.textContent);
    if (raw === '') return;
    // Non-numeric targets (e.g. "22/22") are rendered directly, no animation.
    if (!/^\d+(\.\d+)?$/.test(raw)) {
      node.textContent = raw;
      node.classList.add('os-count-done');
      node._omniCounted = true;
      return;
    }
    var target = parseFloat(raw);
    var suffix = node.dataset.countSuffix || '';
    var decimals = (raw.split('.')[1] || '').length;
    node._omniCounted = true;
    node._omniCounting = true;
    function finish() {
      node.textContent = target.toFixed(decimals) + suffix;
      node.classList.add('os-count-done');
      node._omniCounting = false;
    }
    if (OS.reducedMotion) {
      finish();
      return;
    }
    var start = null;
    var duration = 900;
    // Safety net: renderers whose requestAnimationFrame callbacks never fire
    // (headless capture, heavily throttled background tabs) would otherwise
    // sit at the starting number forever — land on the final value instead.
    var fallback = setTimeout(function () {
      if (node._omniCounting) finish();
    }, duration + 400);
    function frame(ts) {
      if (!node._omniCounting) return;
      if (start === null) start = ts;
      var p = Math.min(1, (ts - start) / duration);
      var eased = 1 - Math.pow(1 - p, 3);
      node.textContent = (target * eased).toFixed(decimals) + suffix;
      if (p < 1) {
        requestAnimationFrame(frame);
      } else {
        clearTimeout(fallback);
        finish();
      }
    }
    requestAnimationFrame(frame);
  }

  // Values for [data-count] nodes are set by page renderers *after* async
  // data loads, so arm a retry that animates as soon as a value appears
  // (and gives up after ~10 s, rendering whatever is there).
  function armCount(node, onDone) {
    if (node.dataset.countValue != null) {
      animateCount(node);
      if (onDone) onDone();
      return;
    }
    var tries = 0;
    (function tick() {
      if (!node.isConnected) return;
      if (node.dataset.countValue != null) {
        animateCount(node);
        if (onDone) onDone();
        return;
      }
      if (++tries > 50) {
        animateCount(node, true);
        return;
      }
      setTimeout(tick, 200);
    })();
  }

  function setupCounts() {
    var nodes = $$('[data-count]');
    if (!nodes.length) return;
    if (OS.reducedMotion || !('IntersectionObserver' in window)) {
      nodes.forEach(function (n) {
        n.classList.add('os-count');
        armCount(n);
      });
      return;
    }
    var observer = new IntersectionObserver(function (entries) {
      entries.forEach(function (entry) {
        if (!entry.isIntersecting) return;
        var node = entry.target;
        if (node.dataset.countValue != null) {
          animateCount(node);
          observer.unobserve(node);
        } else {
          armCount(node, function () { observer.unobserve(node); });
        }
      });
    }, { threshold: 0.4 });
    nodes.forEach(function (n) {
      n.classList.add('os-count');
      observer.observe(n);
    });
  }

  /* Nav anchors (#catalog, #trending, #whats-new, …) point at sections that
     stay hidden until their feed arrives. Browsers refuse to scroll to a
     display:none element, so on a phone the drawer's "Trending" link looked
     completely dead for the seconds the feeds took: the drawer closed, the
     hash changed, nothing moved. Queue the jump and perform it the moment the
     section is revealed. */
  // Fix for #top — scrolling to a huge <main> element caused Safari "A problem repeatedly occurred" crash
  function setupTopAnchorFix() {
    document.addEventListener('click', function (event) {
      var link = event.target.closest && event.target.closest('a[href="#top"]');
      if (!link) return;
      event.preventDefault();
      // Scroll to absolute top without relying on element height
      try {
        if (OS.reducedMotion) {
          window.scrollTo(0, 0);
        } else {
          window.scrollTo({ top: 0, behavior: 'smooth' });
        }
      } catch (e) {
        window.scrollTo(0, 0);
      }
      try {
        history.replaceState(null, '', location.pathname + location.search);
      } catch (e) {}
      if (OS.closeNav) OS.closeNav();
    });
  }

  function setupDeferredAnchors() {
    var pending = null;
    var observer = null;

    function jumpTo(id) {
      var node = document.getElementById(id);
      if (!node || node.hidden) return false;
      node.scrollIntoView({ behavior: OS.reducedMotion ? 'auto' : 'smooth', block: 'start' });
      return true;
    }

    function stopWatching() {
      pending = null;
      if (observer) { observer.disconnect(); observer = null; }
    }

    function watch() {
      if (observer || !pending || !('MutationObserver' in window)) return;
      observer = new MutationObserver(function () {
        if (pending && jumpTo(pending)) stopWatching();
      });
      observer.observe(document.body, { subtree: true, attributes: true, attributeFilter: ['hidden'] });
      // A feed that never lands must not leave a watcher behind.
      setTimeout(stopWatching, 20000);
    }

    document.addEventListener('click', function (event) {
      var link = event.target.closest && event.target.closest('a[href^="#"]');
      if (!link) return;
      var id = decodeURIComponent(link.getAttribute('href').slice(1));
      if (!id) return;
      var node = document.getElementById(id);
      if (!node || !node.hidden) return;
      pending = id;
      watch();
    });
  }

